  init: () => ipcRenderer.invoke('nami:init'),
  range: (q) => ipcRenderer.invoke('nami:range', q),
  days: (q) => ipcRenderer.invoke('nami:days', q),
  current: () => ipcRenderer.invoke('nami:current'),
  appDetail: (q) => ipcRenderer.invoke('nami:appDetail', q),
  overview: (q) => ipcRenderer.invoke('nami:overview', q),
  setIconLevel: (v) => ipcRenderer.invoke('nami:setIconLevel', v),
  setTheme: (t) => ipcRenderer.invoke('nami:setTheme', t),
  setGlass: (v) => ipcRenderer.invoke('nami:setGlass', v),
  setIcon: (v) => ipcRenderer.invoke('nami:setIcon', v),
  setPaused: (on) => ipcRenderer.invoke('nami:setPaused', on),
  cats: () => ipcRenderer.invoke('nami:cats'),
  catSave: (c) => ipcRenderer.invoke('nami:catSave', c),
  catDelete: (id) => ipcRenderer.invoke('nami:catDelete', id),
  catAssign: (a) => ipcRenderer.invoke('nami:catAssign', a),
  pickIcon: (appId, srcPath) => ipcRenderer.invoke('nami:pickIcon', appId, srcPath),
  clearIcon: (appId) => ipcRenderer.invoke('nami:clearIcon', appId),
  renameApp: (appId, name) => ipcRenderer.invoke('nami:renameApp', appId, name),
